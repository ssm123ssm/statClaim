"""Run every scenario and record what StatClaim reports. Needs no Lean.

uv run python replication/evaluate.py          # rewrite results.md and results.json
uv run python replication/evaluate.py --check  # fail if they are out of date
"""

import json
import sys
import tempfile
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from scenarios import SCENARIOS, Scenario  # noqa: E402

from statclaim import __version__  # noqa: E402
from statclaim.contract_reports import study_report  # noqa: E402
from statclaim.language_compiler import compile_source  # noqa: E402
from statclaim.language_runner import check_source  # noqa: E402
from statclaim.language_syntax import Source  # noqa: E402

ORDER = ("rejected", "unresolved", "calculated", "surfaced", "invisible")
MEANING = {
    "rejected": "The file is invalid, with a diagnostic at the cause.",
    "unresolved": "The file is valid but the claim is refused until a requirement is met.",
    "calculated": "An exact calculation shows that the stated target is not met.",
    "surfaced": "Nothing is flagged, but the report lists the assumption that is violated.",
    "invisible": "Nothing is flagged and nothing in the report points at the problem.",
}


def observe(scenario: Scenario) -> dict:
    source = Source(scenario.source, f"{scenario.key}.stat")
    compilation = compile_source(source)
    errors = [d.code for d in compilation.diagnostics if d.severity == "error"]
    if errors:
        return {"outcome": "rejected", "codes": errors, "message": _first(compilation.diagnostics)}
    with tempfile.TemporaryDirectory() as directory:
        # A missing project folder keeps Lean out of it: exact claims that need a
        # proof stay unresolved for that reason only, which is filtered out below.
        report = check_source(source, project=Path(directory), output=Path(directory) / "run")
    obligations = [
        d
        for d in report["diagnostics"]
        if d["severity"] == "obligation" and "needs the Lean backend" not in d["message"]
    ]
    if obligations:
        return {
            "outcome": "unresolved",
            "codes": [d["code"] for d in obligations],
            "message": obligations[0]["message"].splitlines()[0],
        }
    missed = [
        request["report"]
        for request in report["requests"]
        if request["report"].get("decision") in ("target_not_met", "no_feasible_candidate")
    ]
    if missed:
        return {
            "outcome": "calculated",
            "codes": [missed[0]["decision"]],
            "message": _numbers(missed[0]["calculation"]),
        }
    register = study_report(compilation, source.path)["assumption_register"]
    listed = next((item for item in register if item["id"] == scenario.surfaces), None)
    if scenario.surfaces and listed:
        return {
            "outcome": "surfaced",
            "codes": [],
            "message": f"{listed['text']} ({listed['status']})",
        }
    return {"outcome": "invisible", "codes": [], "message": ""}


def _numbers(calculation: dict) -> str:
    """The exact values behind a missed target, rounded for reading."""
    parts = []
    if "power" in calculation:
        met = "met" if calculation["power_target_met"] else "not met"
        parts.append(
            f"exact power {float(calculation['power']['decimal_approximation']):.3f} ({met})"
        )
    if "typeI" in calculation:
        met = "met" if calculation["typeI_target_met"] else "not met"
        parts.append(
            f"Type I error {float(calculation['typeI']['decimal_approximation']):.4f} ({met})"
        )
    if "candidates_evaluated" in calculation:
        parts.append(f"{calculation['candidates_evaluated']} sizes searched, none sufficient")
    return "; ".join(parts)


def _first(diagnostics) -> str:
    return next(d.message for d in diagnostics if d.severity == "error").splitlines()[0]


def run() -> list[dict]:
    rows = []
    for scenario in SCENARIOS:
        observed = observe(scenario)
        agrees = observed["outcome"] == scenario.expected and (
            scenario.code is None or scenario.code in observed["codes"]
        )
        rows.append(
            {
                "key": scenario.key,
                "category": scenario.category,
                "error": scenario.error,
                "expected": scenario.expected,
                "expected_code": scenario.code,
                **observed,
                "as_expected": agrees,
                "note": scenario.note,
            }
        )
    return rows


def render(rows: list[dict]) -> str:
    counts = Counter(row["outcome"] for row in rows)
    lines = [
        "# Evaluation: what StatClaim does with common specification errors",
        "",
        f"Generated by `replication/evaluate.py` with StatClaim {__version__}. "
        "Each scenario injects one error into a valid study file. No Lean is needed.",
        "",
        "| Outcome | Scenarios | Meaning |",
        "| --- | ---: | --- |",
    ]
    lines += [f"| {key} | {counts[key]} | {MEANING[key]} |" for key in ORDER]
    lines += ["", f"Total: {len(rows)} scenarios.", ""]
    for category in dict.fromkeys(row["category"] for row in rows):
        lines += [
            f"## {category}",
            "",
            "| Scenario | The error | Outcome | Code | What StatClaim says |",
            "| --- | --- | --- | --- | --- |",
        ]
        for row in (r for r in rows if r["category"] == category):
            codes = ", ".join(f"`{code}`" for code in dict.fromkeys(row["codes"]))
            said = (row["message"] or row["note"]).replace("|", "\\|")
            lines.append(
                f"| `{row['key']}` | {row['error']} | {row['outcome']} | {codes} | {said} |"
            )
        lines.append("")
    notes = [row for row in rows if row["note"] and row["message"]]
    if notes:
        lines += ["## Notes", ""]
        lines += [f"- `{row['key']}`: {row['note']}" for row in notes]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    rows = run()
    text, data = render(rows), json.dumps(rows, indent=2) + "\n"
    wrong = [row["key"] for row in rows if not row["as_expected"]]
    if wrong:
        print(f"Scenarios that did not behave as stated: {', '.join(wrong)}")
        for row in rows:
            if not row["as_expected"]:
                print(
                    f"  {row['key']}: expected {row['expected']} {row['expected_code']}, "
                    f"observed {row['outcome']} {row['codes']} {row['message']}"
                )
        return 1
    if "--check" in sys.argv:
        stale = (HERE / "results.md").read_text() != text or (
            HERE / "results.json"
        ).read_text() != data
        print("Results are out of date; rerun evaluate.py." if stale else "Results are current.")
        return 1 if stale else 0
    (HERE / "results.md").write_text(text)
    (HERE / "results.json").write_text(data)
    print(f"Wrote {len(rows)} scenarios to replication/results.md and results.json.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
