"""Compare StatClaim's approximate power for cited tests with base R. Needs no R or Lean.

uv run python replication/power.py          # rewrite power_results.md
uv run python replication/power.py --check  # fail if it is out of date or a value drifts

The R values are pinned in tests/fixtures/power_r.json, written by
tests/fixtures/power_r.R. Each case runs through a .stat file and
calculate(meets(...)), so the whole path is checked, not only the formula.
"""

import json
import sys
import tempfile
from fractions import Fraction
from pathlib import Path

from statclaim import __version__
from statclaim.language_runner import check_source
from statclaim.language_syntax import Source

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
FIXTURE = json.loads((ROOT / "tests/fixtures/power_r.json").read_text())
# power.t.test uses the noncentral t; the normal value is a little higher. The pinned
# cases have 400 or more per arm. A logistic regression's power is exact for its Wald test
# (replication/comparison/logistic_wald_r.R checks it against glm on every table);
# power.prop.test approximates a different statistic, so they differ by up to 0.01 here.
TOLERANCE = {"power.t.test": (0, Fraction(1, 1000)), "power.prop.test": (-0.01, 0.01)}


def fraction(value) -> Fraction:
    return Fraction(str(value))


def source(case: dict) -> str:
    one_sided = case["alternative"] == "one.sided"
    n, alpha = case["n"], fraction(case["alpha"])
    if case["function"] == "power.t.test":
        test = "t_test_one_sided" if one_sided else "t_test"
        null = (
            "mean_difference_at_most(model=study, value=0)"
            if one_sided
            else "equal_means(model=study)"
        )
        head = "use models.two_arm_continuous\nuse tests.t\n"
        model = f"two_arm_continuous(n_control={n}, n_treatment={n})"
        point = f"mean_difference(value={fraction(case['delta'])}, sd={fraction(case['sd'])})"
    else:
        test = "logistic_regression_one_sided" if one_sided else "logistic_regression"
        null = (
            "proportion_difference_at_most(model=study, value=0)"
            if one_sided
            else "equal_proportions(model=study)"
        )
        head = "use models.two_arm_binomial\nuse tests.logistic\n"
        model = f"two_arm_binomial(n_control={n}, n_treatment={n})"
        point = (
            f"binomial_rates(p_control={fraction(case['p1'])}, p_treatment={fraction(case['p2'])})"
        )
    return (
        f"{head}use sampling\nuse planning\n"
        f"let study = {model}\n"
        f"let test = {test}(design=fixed(model=study), null={null}, alpha={alpha})\n"
        f"let target = power_target(at={point}, minimum=1/2, maximum_typeI={alpha})\n"
        "let result = calculate(meets(analysis=test, target=target))\n"
    )


def run() -> list[dict]:
    rows = []
    with tempfile.TemporaryDirectory() as directory:
        for index, case in enumerate(FIXTURE["cases"]):
            report = check_source(
                Source(source(case), "power.stat"),
                project=ROOT,
                output=Path(directory) / f"case-{index}",
            )
            calculation = report["requests"][0]["report"]["calculation"]
            statclaim = Fraction(calculation["power"]["fraction"])
            low, high = TOLERANCE[case["function"]]
            difference = statclaim - fraction(case["power"])
            rows.append(
                {
                    **case,
                    "status": report["status"],
                    "statclaim": calculation["power"]["decimal_approximation"],
                    "difference": f"{float(difference):+.6f}",
                    "within_tolerance": report["status"] == "calculated"
                    and low <= difference <= high,
                }
            )
    return rows


def describe(row: dict) -> str:
    sides = "one-sided" if row["alternative"] == "one.sided" else "two-sided"
    if row["function"] == "power.t.test":
        return f"n = {row['n']}, delta = {row['delta']}, sd = {row['sd']}, {sides} {row['alpha']}"
    return f"n = {row['n']}, p = {row['p1']} vs {row['p2']}, {sides} {row['alpha']}"


def render(rows: list[dict]) -> str:
    lines = [
        "# Approximate power for cited tests, against base R",
        "",
        f"Generated by `replication/power.py` with StatClaim {__version__}. R values are "
        f"pinned in `tests/fixtures/power_r.json` ({FIXTURE['r_version']}, base stats only).",
        "",
        "Each StatClaim value is `calculate(meets(...))` on a t-test or a logistic regression, "
        "with status `calculated`. `power.t.test` uses the noncentral t distribution, so the "
        "normal value may be higher by less than 0.001 at these sizes. A logistic "
        "regression's power is summed exactly over both arms' counts for its Wald test, and "
        "matches glm on every table (`replication/comparison/logistic_wald_r.R`); "
        "`power.prop.test` is a normal approximation to a related statistic, so the two "
        "differ by up to 0.01 at these sizes.",
        "",
        "| R function | Case (n per arm) | R | StatClaim | Difference | Within tolerance |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| `{row['function']}` | {describe(row)} | {row['power']:.6f} | {row['statclaim']} "
            f"| {row['difference']} | {'yes' if row['within_tolerance'] else 'no'} |"
        )
    return "\n".join([*lines, ""])


def main() -> int:
    rows = run()
    text = render(rows)
    outside = [describe(row) for row in rows if not row["within_tolerance"]]
    if outside:
        print(f"Outside the stated tolerance: {'; '.join(outside)}")
        return 1
    if "--check" in sys.argv:
        stale = (HERE / "power_results.md").read_text() != text
        print("power_results.md is out of date." if stale else "power_results.md is current.")
        return 1 if stale else 0
    (HERE / "power_results.md").write_text(text)
    print(f"Wrote {len(rows)} cases to replication/power_results.md.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
