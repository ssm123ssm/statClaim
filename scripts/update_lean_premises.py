"""Write StatClaim/Generated/Methods.lean from the method registry.

uv run python scripts/update_lean_premises.py          # rewrite the file
uv run python scripts/update_lean_premises.py --check  # fail if it is out of date

The registry in src/statclaim/methods stays the one source of truth. Each cited test
becomes a Lean record of what a contract reads about it: the null forms it supports, its
scope, its minimum sizes and the ids of the assumptions reported with every result. Its
guarantee enters a program as a LevelPremise of that scope
(StatClaim/Interface/Premises.lean). See docs/proposals/lean-translation.md.
"""

import re
import sys
from fractions import Fraction
from pathlib import Path

from statclaim.composition import CITED_RULES
from statclaim.methods import METHODS, NULL_FORMS, OBSERVATIONAL, OUTCOMES
from statclaim.methods.assumptions import CONTRADICTED_BY

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "StatClaim/Generated/Methods.lean"
SOURCES = {"cited": "literature", "declared": "author"}
SCOPES = {"finite_sample": "finiteSample", "asymptotic": "largeSample"}
SCOPE_WORDS = {"finite_sample": "finite-sample", "asymptotic": "large-sample"}
# A one-sided null favours the treatment on one side; a two-sided one is an equality.
SHAPES = {None: "equal", "higher": "atMost", "lower": "atLeast"}
# The project's source guard rejects these words anywhere in Lean, comments included.
FORBIDDEN = re.compile(r"\b(sorry|admit|axiom)\b")
IDENTIFIER = re.compile(r"[a-z][a-z0-9_]*")

PREAMBLE = """\
module

public import StatClaim.Interface.Outcomes
public import StatClaim.Interface.Premises

/-!
Generated by scripts/update_lean_premises.py from the method registry in
src/statclaim/methods. Do not edit: change the registry and regenerate.

Each entry records what a contract reads about a cited test: the null forms it
supports, its scope, its minimum sizes and the ids of the assumptions reported
with every result. Its guarantee enters a program as a `LevelPremise` of that
scope. Entries carry no proof and no guarantee by themselves.

Trusted: what an entry says enters the premises and contracts of every certificate.
-/

@[expose] public section

set_option autoImplicit false

namespace StatClaim.Generated

open StatClaim.Interface
"""

RECORDS = """\
/-- A cited test of a two-arm trial, as the method registry describes it. -/
structure TrialMethod where
  key : String
  version : Nat
  source : Source
  scope : Scope
  outcome : OutcomeKind
  nulls : List NullKey
  /-- A value the null must have, such as a zero difference. -/
  nullValue : Option ℚ
  minPerArm : Nat
  minTotal : Nat
  /-- What the minimum sizes count. -/
  unit : CountUnit
  assumptions : List String

/-- A cited test of association in an observational study. -/
structure AssociationMethod where
  key : String
  version : Nat
  source : Source
  scope : Scope
  designs : List ObservationalDesign
  outcomeScales : List Scale
  exposureScales : List Scale
  surveys : List Survey
  covariates : Bool
  minTotal : Nat
  minClusters : Option Nat
  assumptions : List String

/-- How the members of a cited procedure relate: looks that ask one question, or a family
of questions. -/
inductive ProcedureQuestion where
  | looks
  | family
  deriving DecidableEq, Repr

/-- What a cited procedure asks of its members' levels: each the whole level, or at most it. -/
inductive MemberLevels where
  | equal
  | atMost
  deriving DecidableEq, Repr
"""


def identifier(name: str) -> str:
    if not IDENTIFIER.fullmatch(name):
        raise ValueError(f"{name!r} cannot be a Lean name.")
    return name


def enum(name: str, doc: str, cases) -> list[str]:
    lines = [f"/-- {doc} -/", f"inductive {name} where"]
    lines += [f"  | {identifier(case)}" for case in cases]
    return [*lines, "  deriving DecidableEq, Repr", ""]


def mapping(name: str, doc: str, source: str, target: str, pairs) -> list[str]:
    lines = [f"/-- {doc} -/", f"def {source}.{name} : {source} → {target}"]
    lines += [f"  | .{identifier(key)} => {value}" for key, value in pairs]
    return [*lines, ""]


def rational(value: Fraction | None) -> str:
    if value is None:
        return "none"
    value = Fraction(value)
    if value.denominator == 1:
        return f"some ({value.numerator} : ℚ)"
    return f"some (({value.numerator} : ℚ) / {value.denominator})"


def items(prefix: str, values) -> str:
    return "[" + ", ".join(f"{prefix}.{identifier(v)}" for v in values) + "]"


def strings(values) -> str:
    return "[" + ", ".join(f'"{identifier(v)}"' for v in values) + "]"


def doc(method, scope: str) -> str:
    source = "author-declared" if method.grade == "declared" else "cited"
    return f"/-- {method.title}. {SCOPE_WORDS[scope].capitalize()} guarantee, {source}. -/"


def trial(method) -> list[str]:
    return [
        doc(method, method.scope),
        f"def {identifier(method.key)} : TrialMethod where",
        f'  key := "{method.key}"',
        f"  version := {method.version}",
        f"  source := .{SOURCES[method.grade]}",
        f"  scope := .{SCOPES[method.scope]}",
        f"  outcome := .{identifier(method.outcome)}",
        f"  nulls := {items('NullKey', method.nulls)}",
        f"  nullValue := {rational(method.null_value)}",
        f"  minPerArm := {method.min_per_arm}",
        f"  minTotal := {method.min_total}",
        f"  unit := .{identifier(method.unit)}",
        f"  assumptions := {strings(a.id for a in method.assumptions)}",
        "",
    ]


def association(method) -> list[str]:
    clusters = "none" if method.min_clusters is None else f"some {method.min_clusters}"
    return [
        doc(method, method.scope),
        f"def {identifier(method.key)} : AssociationMethod where",
        f'  key := "{method.key}"',
        f"  version := {method.version}",
        f"  source := .{SOURCES[method.grade]}",
        f"  scope := .{SCOPES[method.scope]}",
        f"  designs := {items('ObservationalDesign', method.designs)}",
        f"  outcomeScales := {items('Scale', method.outcome_scales)}",
        f"  exposureScales := {items('Scale', method.exposure_scales)}",
        f"  surveys := {items('Survey', method.surveys)}",
        f"  covariates := {'true' if method.covariates else 'false'}",
        f"  minTotal := {method.min_total}",
        f"  minClusters := {clusters}",
        f"  assumptions := {strings(a.id for a in method.assumptions)}",
        "",
    ]


def text(value: str) -> str:
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", value):
        raise ValueError(f"{value!r} cannot be a field of a cited procedure.")
    return f'"{value}"'


def procedures() -> list[str]:
    """The cited procedures that combine tests: what the semantics reads about each."""
    rules = [rule.key for rule in CITED_RULES]
    lines = enum("Procedure", "The cited procedures that combine tests.", rules)
    lines += mapping(
        "fields",
        "The constant entries of each procedure's canonical form, method first.",
        "Procedure",
        "List (String × String)",
        (
            (
                rule.key,
                "[" + ", ".join(f"({text(k)}, {text(v)})" for k, v in rule.fields) + "]",
            )
            for rule in CITED_RULES
        ),
    )
    lines += mapping(
        "question",
        "Whether the members are looks at one question or a family of questions.",
        "Procedure",
        "ProcedureQuestion",
        ((rule.key, f".{rule.question}") for rule in CITED_RULES),
    )
    lines += mapping(
        "levels",
        "What the procedure asks of its members' levels.",
        "Procedure",
        "MemberLevels",
        ((rule.key, ".equal" if rule.levels == "equal" else ".atMost") for rule in CITED_RULES),
    )
    lines += mapping(
        "graph",
        "Whether the procedure takes weights and transitions.",
        "Procedure",
        "Bool",
        ((rule.key, "true" if rule.graph else "false") for rule in CITED_RULES),
    )
    lines += mapping(
        "scope",
        "The scope of the cited guarantee; none when it is finite-sample if every member is.",
        "Procedure",
        "Option Scope",
        (
            (rule.key, "none" if rule.scope == "members" else f"some .{SCOPES[rule.scope]}")
            for rule in CITED_RULES
        ),
    )
    lines += [
        "/-- Every cited procedure, in registry order. -/",
        "def procedures : List Procedure :=",
        "  " + items("Procedure", rules),
        "",
    ]
    return lines


def render() -> str:
    trials, associations = list(METHODS.values()), list(OBSERVATIONAL.values())
    designs = sorted({d for m in associations for d in m.designs})
    scales = sorted({s for m in associations for s in (*m.outcome_scales, *m.exposure_scales)})
    surveys = sorted({s for m in associations for s in m.surveys})
    units = sorted({m.unit for m in trials})
    lines = [PREAMBLE]
    lines += enum("OutcomeKind", "The outcome kinds of two-arm models.", OUTCOMES)
    lines += mapping(
        "constructor",
        "The constructor of each outcome kind's two-arm model, as the canonical program names it.",
        "OutcomeKind",
        "String",
        ((key, f'"{identifier(outcome.constructor)}"') for key, outcome in OUTCOMES.items()),
    )
    lines += enum("NullKey", "The null forms of two-arm outcomes.", NULL_FORMS)
    lines += mapping(
        "key",
        "The name of each null form, as the canonical program writes it.",
        "NullKey",
        "String",
        ((key, f'"{identifier(key)}"') for key in NULL_FORMS),
    )
    lines += mapping(
        "outcome",
        "The outcome each null form belongs to.",
        "NullKey",
        "OutcomeKind",
        ((key, f".{outcome.key}") for key, (outcome, _) in NULL_FORMS.items()),
    )
    lines += mapping(
        "shape",
        "The shape of each null form; one without a value uses zero.",
        "NullKey",
        "NullShape",
        ((key, f".{SHAPES[form.favours]}") for key, (_, form) in NULL_FORMS.items()),
    )
    lines += mapping(
        "takesValue",
        "Whether a null form takes a value.",
        "NullKey",
        "Bool",
        ((key, "true" if form.takes_value else "false") for key, (_, form) in NULL_FORMS.items()),
    )
    lines += enum("CountUnit", "What a test's minimum sizes count.", units)
    lines += enum(
        "DesignFeature",
        "Declared design features a test's assumptions can contradict.",
        CONTRADICTED_BY,
    )
    lines += mapping(
        "contradicts",
        "The assumptions each design feature contradicts: a test assuming one of them does "
        "not fit a design with the feature.",
        "DesignFeature",
        "List String",
        ((feature, strings(ids)) for feature, ids in CONTRADICTED_BY.items()),
    )
    lines += enum("ObservationalDesign", "The observational designs cited tests fit.", designs)
    lines += mapping(
        "key",
        "Each case's name, as the canonical program writes it.",
        "ObservationalDesign",
        "String",
        ((case, f'"{identifier(case)}"') for case in designs),
    )
    lines += enum("Scale", "The scales of an observational outcome or exposure.", scales)
    lines += mapping(
        "key",
        "Each case's name, as the canonical program writes it.",
        "Scale",
        "String",
        ((case, f'"{identifier(case)}"') for case in scales),
    )
    lines += enum("Survey", "The sampling designs of an observational study.", surveys)
    lines += mapping(
        "key",
        "Each case's name, as the canonical program writes it.",
        "Survey",
        "String",
        ((case, f'"{identifier(case)}"') for case in surveys),
    )
    lines += [RECORDS]
    lines += procedures()
    lines += ["namespace Methods", ""]
    for method in trials:
        lines += trial(method)
    for method in associations:
        lines += association(method)
    lines += ["end Methods", ""]
    lines += [
        "/-- Every cited trial test, in registry order. -/",
        "def trialMethods : List TrialMethod :=",
        "  " + items("Methods", (m.key for m in trials)),
        "",
        "/-- Every cited test of association, in registry order. -/",
        "def associationMethods : List AssociationMethod :=",
        "  " + items("Methods", (m.key for m in associations)),
        "",
        "end StatClaim.Generated",
        "",
    ]
    text = "\n".join(lines)
    if FORBIDDEN.search(text):
        raise ValueError("A registry text contains a word the Lean source guard rejects.")
    return text


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.is_file() or TARGET.read_text() != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run scripts/update_lean_premises.py")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is current.")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text)
    print(f"Wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
