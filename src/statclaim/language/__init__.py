"""Typed statistical objects and module-driven elaboration of .stat files.

No Python or Lean source in a user file is executed. Module builders lower the
supported objects to the same validated requests as the TOML and Lean routes.

The modules, in the order a program flows through them; each imports only those
before it:

    core        parameters, constructors, modules and errors
    ir          the typed objects: models, designs, analyses, claims, programs
    normalize   their canonical JSON form, for derivations and reports
    designs     assignments, outcomes and two-arm models
    analyses    tests, observational studies, results, families and sequences
    points      planning points and targets
    checks      whether a point and target fit an analysis; meets(...)
    searches    sample-size searches, single-arm and two-stage designs
    operations  verify, calculate and simulate
    registry    every module a .stat file can use, with its constructors
    elaborate   from a parsed program to typed objects and requests

Other modules import from statclaim.language, which re-exports the names in __all__.
"""

